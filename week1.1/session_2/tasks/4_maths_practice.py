# Work out the answers to the three maths problems:
# Python operators: * multiply, / divide (gives a float), ** power (NOT ^)

# 1: (4 x 8) x 6
answer1 = (4 * 8) * 6
print(f"1: {answer1}")   # 192


# 2: (2^3) / (8/3)
answer2 = (2 ** 3) / (8 / 3)
print(f"2: {answer2}")   # 3.0


# 3: 27^2 x 19/4
answer3 = 27 ** 2 * 19 / 4
print(f"3: {answer3}")   # 3462.75
