fruit = ["cherry", "strawberry", "melon", "grape", "apple"]

# Sort list
# sort() changes the list itself (in place) into alphabetical order
fruit.sort()
print(fruit)

# Reverse order of list items
fruit.reverse()
print(fruit)

# Remove all items
# clear() empties the list, leaving []
fruit.clear()
print(fruit)
